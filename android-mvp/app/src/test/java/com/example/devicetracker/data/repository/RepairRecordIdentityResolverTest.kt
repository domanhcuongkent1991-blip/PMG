package com.example.devicetracker.data.repository

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

/**
 * Unit tests cho RepairRecordIdentityResolver.
 *
 * Test cases:
 * 1. exact match - record_id khớp chính xác với local recordId
 * 2. base id match duy nhất - repair recordId là base và chỉ có 1 local match
 * 3. ambiguous skip - nhiều local records cùng base thì skip
 * 4. not found skip - record không tồn tại trong local thì skip
 * 5. strip prefix readonly-dmbt-{sheetId}-...
 * 6. record không có prefix giữ nguyên
 * 7. malformed namespace giữ nguyên
 */
class RepairRecordIdentityResolverTest {

    // ========== stripDmbtNamespace Tests ==========

    @Test
    fun stripDmbtNamespace_withNamespacedRecordId_stripsCorrectly() {
        // "readonly-dmbt-{sheetId}-{baseId}" → "{baseId}"
        assertEquals(
            "TB001-001",
            RepairRecordIdentityResolver.stripDmbtNamespace("readonly-dmbt-1607125070-TB001-001")
        )

        assertEquals(
            "TB002-002",
            RepairRecordIdentityResolver.stripDmbtNamespace("readonly-dmbt-1383308512-TB002-002")
        )

        assertEquals(
            "XYZ-ABC",
            RepairRecordIdentityResolver.stripDmbtNamespace("readonly-dmbt-849979183-XYZ-ABC")
        )
    }

    @Test
    fun stripDmbtNamespace_withBaseRecordId_unchanged() {
        // Không có prefix → giữ nguyên
        assertEquals(
            "TB001-001",
            RepairRecordIdentityResolver.stripDmbtNamespace("TB001-001")
        )

        assertEquals(
            "TB002-002",
            RepairRecordIdentityResolver.stripDmbtNamespace("TB002-002")
        )
    }

    @Test
    fun stripDmbtNamespace_withAutoGeneratedId_unchanged() {
        // "dmbt-auto-" là prefix khác, không strip
        assertEquals(
            "dmbt-auto-TB001-001",
            RepairRecordIdentityResolver.stripDmbtNamespace("dmbt-auto-TB001-001")
        )

        assertEquals(
            "dmbt-auto-row-123",
            RepairRecordIdentityResolver.stripDmbtNamespace("dmbt-auto-row-123")
        )
    }

    @Test
    fun stripDmbtNamespace_withEmptyString_unchanged() {
        assertEquals("", RepairRecordIdentityResolver.stripDmbtNamespace(""))
    }

    @Test
    fun stripDmbtNamespace_malformed_missingBase_unchanged() {
        // "readonly-dmbt-1607125070" - thiếu base recordId → giữ nguyên
        assertEquals(
            "readonly-dmbt-1607125070",
            RepairRecordIdentityResolver.stripDmbtNamespace("readonly-dmbt-1607125070")
        )
    }

    @Test
    fun stripDmbtNamespace_malformed_nonNumericSheetId_unchanged() {
        // "readonly-dmbt-ABC-TB001-001" - non-numeric sheetId → giữ nguyên
        assertEquals(
            "readonly-dmbt-ABC-TB001-001",
            RepairRecordIdentityResolver.stripDmbtNamespace("readonly-dmbt-ABC-TB001-001")
        )
    }

    @Test
    fun stripDmbtNamespace_malformed_negativeSheetId_unchanged() {
        // "-123-TB001-001" - sheetId không hợp lệ → giữ nguyên
        assertEquals(
            "readonly-dmbt--123-TB001-001",
            RepairRecordIdentityResolver.stripDmbtNamespace("readonly-dmbt--123-TB001-001")
        )
    }

    // ========== resolveRepairRecordId Tests ==========

    @Test
    fun resolveRepairRecordId_exactMatch_returnsMatchedId() {
        // Arrange
        val repairRecordId = "readonly-dmbt-1607125070-TB001-001"
        val localRecordIds = listOf(
            "readonly-dmbt-1607125070-TB001-001",
            "readonly-dmbt-1383308512-TB002-001"
        )

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert - dùng assertEquals để kiểm tra giá trị chuỗi
        assertEquals(repairRecordId, result)
    }

    @Test
    fun resolveRepairRecordId_exactMatch_baseRecordId_returnsMatchedId() {
        // Arrange: repair nhập base recordId, local có đúng 1 record
        val repairRecordId = "TB001-001"
        val localRecordIds = listOf(
            "readonly-dmbt-1607125070-TB001-001",
            "readonly-dmbt-1383308512-TB002-001"
        )

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert: vì chỉ có 1 match nên trả về recordId đó
        assertEquals("readonly-dmbt-1607125070-TB001-001", result)
    }

    @Test
    fun resolveRepairRecordId_ambiguous_returnsNull() {
        // Arrange: cùng base recordId có 2 records ở 2 sheets khác nhau
        val repairRecordId = "TB001-001"
        val localRecordIds = listOf(
            "readonly-dmbt-1607125070-TB001-001",  // DMBT 2026
            "readonly-dmbt-1383308512-TB001-001"   // DMBT T4.2026
        )

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert: ambiguous → skip
        assertNull(result)
    }

    @Test
    fun resolveRepairRecordId_notFound_returnsNull() {
        // Arrange
        val repairRecordId = "UNKNOWN-999"
        val localRecordIds = listOf(
            "readonly-dmbt-1607125070-TB001-001",
            "readonly-dmbt-1383308512-TB002-001"
        )

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert: not found → skip
        assertNull(result)
    }

    @Test
    fun resolveRepairRecordId_emptyRepairRecordId_returnsNull() {
        // Arrange
        val repairRecordId = ""
        val localRecordIds = listOf("readonly-dmbt-1607125070-TB001-001")

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert
        assertNull(result)
    }

    @Test
    fun resolveRepairRecordId_emptyLocalRecordIds_returnsNull() {
        // Arrange
        val repairRecordId = "TB001-001"
        val localRecordIds = emptyList<String>()

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert
        assertNull(result)
    }

    @Test
    fun resolveRepairRecordId_baseRecordId_defaultSheet_matches() {
        // Arrange: default sheet không có namespace, base = full recordId
        val repairRecordId = "TB001-001"
        val localRecordIds = listOf(
            "TB001-001",  // Default sheet - không có prefix
            "readonly-dmbt-1383308512-TB002-001"
        )

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert: exact match với default sheet record
        assertEquals("TB001-001", result)
    }

    @Test
    fun resolveRepairRecordId_autoGeneratedRecordId_matches() {
        // Arrange
        val repairRecordId = "dmbt-auto-TB001-001"
        val localRecordIds = listOf(
            "dmbt-auto-TB001-001",
            "readonly-dmbt-1383308512-TB002-001"
        )

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert
        assertEquals("dmbt-auto-TB001-001", result)
    }

    @Test
    fun resolveRepairRecordId_sheetIdWithoutDash_matchesBase() {
        // Arrange: edge case - nếu baseId không có dash
        val repairRecordId = "TB001"
        val localRecordIds = listOf(
            "readonly-dmbt-1607125070-TB001"  // baseId không có second dash
        )

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert
        assertEquals("readonly-dmbt-1607125070-TB001", result)
    }

    @Test
    fun resolveRepairRecordId_exactMatchBeforeStrip_alwaysWins() {
        // Arrange: có cả exact match và base match
        val repairRecordId = "TB001-001"
        val localRecordIds = listOf(
            "TB001-001",  // Exact match với default sheet
            "readonly-dmbt-1607125070-TB001-001"  // Base match nhưng không exact
        )

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert: exact match thắng
        assertEquals("TB001-001", result)
    }

    // ========== Malformed Namespace Tests ==========

    @Test
    fun resolveRepairRecordId_malformedMissingBase_notFound() {
        // Arrange: malformed recordId "readonly-dmbt-1607125070" (thiếu base)
        val repairRecordId = "readonly-dmbt-1607125070"
        val localRecordIds = listOf(
            "readonly-dmbt-1607125070-TB001-001",
            "readonly-dmbt-1383308512-TB002-001"
        )

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert: malformed → không strip → không khớp → null
        assertNull(result)
    }

    @Test
    fun resolveRepairRecordId_malformedNonNumericSheetId_notFound() {
        // Arrange: malformed recordId "readonly-dmbt-ABC-TB001-001"
        val repairRecordId = "readonly-dmbt-ABC-TB001-001"
        val localRecordIds = listOf(
            "readonly-dmbt-1607125070-TB001-001",
            "readonly-dmbt-1383308512-TB002-001"
        )

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert: non-numeric sheetId → không strip → không khớp → null
        assertNull(result)
    }

    @Test
    fun resolveRepairRecordId_malformedNegativeSheetId_notFound() {
        // Arrange: malformed recordId "readonly-dmbt--123-TB001-001"
        val repairRecordId = "readonly-dmbt--123-TB001-001"
        val localRecordIds = listOf(
            "readonly-dmbt-1607125070-TB001-001",
            "readonly-dmbt-1383308512-TB002-001"
        )

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            repairRecordId,
            localRecordIds
        )

        // Assert: negative sheetId → không strip → không khớp → null
        assertNull(result)
    }

    @Test
    fun resolveRepairRecordId_malformedButExactMatchStillWins() {
        // Arrange: dù malformed nhưng nếu exact match thì vẫn trả về
        val malformedRecordId = "readonly-dmbt-1607125070"
        val localRecordIds = listOf(
            "readonly-dmbt-1607125070",  // Exact match
            "readonly-dmbt-1383308512-TB002-001"
        )

        // Act
        val result = RepairRecordIdentityResolver.resolveRepairRecordId(
            malformedRecordId,
            localRecordIds
        )

        // Assert: exact match thắng
        assertEquals("readonly-dmbt-1607125070", result)
    }
}
